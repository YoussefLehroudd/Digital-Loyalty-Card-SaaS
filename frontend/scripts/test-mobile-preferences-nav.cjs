const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path");
const src=(p)=>fs.readFileSync(path.join(__dirname,"../src",p),"utf8");
const settings=src("app/user/settings/page.tsx");
const tabs=src("components/customer-app/customer-bottom-nav.tsx");
const customerLayout=src("components/customer-app/customer-layout.tsx");
const userLayout=src("components/customer-app/customer-area-layout-client.tsx");
const css=src("app/globals.css");

assert.match(settings,/role="switch" aria-checked=\{checked\}/,"Preference toggles are accessible switches");
assert.match(settings,/flex w-full min-w-0 items-center gap-3 overflow-hidden/,"Mobile switch rows must respect container width");
assert.match(settings,/flex min-w-0 flex-1 flex-col/,"Long notification text must wrap instead of pushing switches offscreen");
assert.match(settings,/h-6 w-11 min-w-11 shrink-0/,"Switch width cannot collapse when push description is longer");
assert.match(settings,/relative inline-block h-6 w-11/,"Toggle thumb is positioned within a fixed-size track");
assert.ok(settings.includes('checked={emailUpdates}')&&settings.includes('checked={rewardAlerts}')&&settings.includes('checked={promotions}')&&settings.includes('checked={pushEnabled}'),"All four settings preserved");
assert.match(userLayout,/<CustomerGuard>\{children\}<CustomerBottomNav\s*\/>/,"Mobile bar belongs to persistent customer layout");
assert.match(tabs,/storageKey=\(userId:string\)/,"Separate saved scroll offsets per signed-in account");
assert.match(tabs,/sessionStorage\.setItem/,"Persist scroll offset across PWA navigations/reloads");
assert.match(tabs,/sessionStorage\.getItem/,"Restore saved offset after PWA remount");
assert.match(tabs,/useLayoutEffect\(\(\)=>\{/,"Restore before browser paint, without jump animation");
assert.match(tabs,/strip\.scrollLeft=loadOffset\(userId\)/,"Restore the actual horizontal scroll position");
assert.match(tabs,/onScroll=\{saveOffset\}/,"Track swipes without rerendering");
assert.match(tabs,/onClick=\{flushOffset\}/,"Capture most recent offset before route changes");
assert.match(tabs,/onTouchEnd=\{saveOffset\}/,"Capture mobile gestures");
assert.ok(!tabs.includes("scrollIntoView("),"No automatic scroll-to-active call that resets user's position");
assert.ok(!customerLayout.includes("customer-bottom-nav-scroll"),"Do not mount another bottom bar in every page");
assert.match(css,/\.customer-bottom-nav-scroll \{[\s\S]*overflow-anchor: none/,"Prevent browser scroll anchoring");
assert.match(css,/\.customer-bottom-nav-scroll::-webkit-scrollbar[\s\S]*display: none/,"Scrollbar remains hidden");
console.log("PASS mobile preferences: fixed-width switches and wrapping labels; nav restores last offset on remount, with no visible scrollbar");
